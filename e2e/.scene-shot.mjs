import { chromium } from "playwright";
import { join } from "node:path";
import { createConfirmedAccount, signInContext } from "./lib/accounts.mjs";
import { startMailbox } from "./lib/mail.mjs";
const OUT = process.argv[2];
const BASE = "http://localhost:3000";
const mailbox = await startMailbox();
const browser = await chromium.launch();
const account = await createConfirmedAccount(browser, BASE, mailbox, { name: "Scene Shots" });
const context = await browser.newContext({ viewport: { width: 1536, height: 960 } });
await signInContext(context, BASE, account);
const page = await context.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => m.type() === "error" && errors.push("console: " + m.text()));
await page.goto(`${BASE}/studio/scenes`, { waitUntil: "networkidle" });
await page.screenshot({ path: join(OUT, "scenes-empty.png") });
await page.getByRole("button", { name: "Sample scene" }).click();
await page.waitForURL("**/studio/scenes/**", { timeout: 60000 });
await page.locator("[data-save-state=saved]").waitFor({ timeout: 30000 });
await page.waitForTimeout(2500);
await page.screenshot({ path: join(OUT, "scene-editor.png") });
await page.locator('[data-backdrop="marble"]').click();
await page.waitForTimeout(1500);
await page.screenshot({ path: join(OUT, "scene-marble.png") });
await page.getByRole("button", { name: "Animate scene" }).first().click();
await page.getByRole("dialog", { name: "Choose a motion style" }).waitFor();
await page.waitForTimeout(2500);
await page.screenshot({ path: join(OUT, "animate-dialog.png") });
console.log("errors:", errors.join(" | ") || "none");
await browser.close();
await mailbox.close();
